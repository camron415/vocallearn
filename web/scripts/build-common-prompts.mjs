function unique(list) {
  const seen = new Set();
  const out = [];
  for (const raw of list) {
    const text = String(raw).replace(/\s+/g, " ").trim();
    if (!text) continue;
    const key = text.toLowerCase();
    if (seen.has(key)) continue;
    seen.add(key);
    out.push(text);
  }
  return out;
}

const combos = [];
for (const opener of OPENERS) {
  for (const topic of TOPICS) {
    const body = topic.charAt(0).toLowerCase() + topic.slice(1);
    if (opener === "What's") {
      combos.push(`What's ${body}?`);
    } else if (opener === "Why does") {
      combos.push(`Why does ${body}?`);
    } else if (opener === "Can you explain") {
      combos.push(`Can you explain ${body}?`);
    } else {
      combos.push(`${opener} ${body}?`);
    }
    for (const tail of TAILS) {
      if (!tail) continue;
      if (opener === "What's") combos.push(`What's ${body}${tail}?`);
    }
  }
}

const all = unique([...HEAD, ...EXTRA, ...combos]);
const ranked = all.slice(0, 2000).map((text, i) => ({
  text,
  freq: 2000 - i,
}));

const dir = dirname(fileURLToPath(import.meta.url));
const dest = join(dir, "../src/data/common-prompts.json");
writeFileSync(dest, JSON.stringify(ranked, null, 0));
console.log(`wrote ${ranked.length} prompts to ${dest}`);
